// L3's own icon sprite (0.5.2): the Lucide symbols for every icon name the editor's shell and views use, written into
// src/iso-editor/ui/plain-icons.ts with Lucide's ISC notice. L3 can't read files in a browser, so the symbols are a
// module of their own; this script makes it from the vendored copy (vendor/lucide-static, ISC) and
// test/plain-skin.test.ts checks that the module is what this script would write and that it covers every name used.
//
// usage: node --experimental-strip-types scripts/plain-icons.ts [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './layers.ts';

/** every icon L3 asks for by name: the shell's buttons, the tree, the menus, the panel, the palette's default */
export const PLAIN_ICON_NAMES = ['arrow-up-right', 'box', 'chevron-down', 'chevron-right', 'circle-dot', 'circle-x', 'clipboard', 'clipboard-paste',
  'code-xml', 'copy', 'layers', 'link', 'list', 'list-tree', 'panel-right', 'pencil', 'plus', 'rotate-ccw', 'trash-2', 'triangle-alert', 'x'] as const;

const LUCIDE = join(ROOT, 'vendor/lucide-static');
export const OUT = join(ROOT, 'src/iso-editor/ui/plain-icons.ts');

export function plainIconsModule(): string {
  const version = /lucide-static v([\d.]+)/.exec(readFileSync(join(LUCIDE, 'box.svg'), 'utf8'))?.[1] ?? '?';
  const licence = readFileSync(join(LUCIDE, 'LICENSE'), 'utf8').trim().split('\n').map(l => `// ${l}`.trimEnd()).join('\n');
  const symbols = PLAIN_ICON_NAMES.map(name => {
    const svg = readFileSync(join(LUCIDE, `${name}.svg`), 'utf8');
    const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, ' ').trim();
    return `  '${name}': '${inner.replaceAll("'", "\\'")}',`;
  });
  return `// GENERATED by scripts/plain-icons.ts from lucide-static v${version} (the vendored copy the script names): do not edit.
// L3's own icons: one <symbol id="se-i-NAME"> for every name the editor's shell and views use (PLAIN_ICONS), so a
// host with no sprite of its own still has them. setupFor gives PLAIN_SPRITE as the setup's sprite by default.
//
// Lucide's licence (the symbols below are Lucide's):
${licence}

/** each icon's SVG body, by name (Lucide, ISC) */
export const PLAIN_ICON_SVG: Record<string, string> = {
${symbols.join('\n')}
};
/** the names L3 uses */
export const PLAIN_ICONS: readonly string[] = Object.keys(PLAIN_ICON_SVG);
/** symbols of a sprite: one per icon, with the id icon() and the shell's markup use */
export const iconSymbols = (svgs: Record<string, string>): string =>
  Object.entries(svgs).map(([n, body]) => \`<symbol id="se-i-\${n}" viewBox="0 0 24 24">\${body}</symbol>\`).join('');
/** a sprite of symbols, as the setup's sprite (mountEditor puts it in the editor's root) */
export const spriteOf = (symbols: string): string =>
  \`<svg xmlns="http://www.w3.org/2000/svg" class="sprite" aria-hidden="true" focusable="false">\${symbols}</svg>\`;
/** L3's sprite: every icon it uses */
export const PLAIN_SPRITE = spriteOf(iconSymbols(PLAIN_ICON_SVG));
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = plainIconsModule();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== want) { console.error(`${OUT} is out of date: run scripts/plain-icons.ts`); process.exit(1); }
  } else writeFileSync(OUT, want);
  console.log(`${PLAIN_ICON_NAMES.length} icons`);
}
